'use strict';
const { selectDesktopPage, setGatewayEnabled } = require('./desktop-page-menu.cjs');
// End-to-end with a test-owned gateway and fake NATAPP executable only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { _electron: electron } = require('playwright');
const { ControllerGatewayManager } = require('../desktop/controller-manager.cjs');
const { countNatappProcesses } = require('../desktop/native-helper.cjs');
const { waitForShellState } = require('./wait-shell-state.cjs');
const root = path.resolve(__dirname, '..'), stage = path.join(root, '.local', 'hajimink-stage');
const binary = process.env.HAJIMINK_DESKTOP_BINARY || require('electron'), packaged = !!process.env.HAJIMINK_DESKTOP_BINARY;
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'hajimink-natapp-ui-'));
const data = path.join(temp, '用户资料'), files = path.join(temp, '客户端 文件');
const exe = path.join(files, 'natapp.exe'), config = path.join(files, 'config.ini');
const fakeSecret = 'fixture-only-secret-not-in-state';
let application, page, manager;
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const { freePort } = require('./test-network.cjs');
async function quitDesktop() {
  if (!application) return;
  const current = application, processHandle = current.process();
  const exited = new Promise(resolve => { if (processHandle.exitCode !== null) resolve(); else processHandle.once('exit', resolve); });
  await current.evaluate(({ app }) => { setTimeout(() => app.quit(), 50); });
  await Promise.race([exited, delay(12000).then(() => { throw new Error('Fixture desktop did not exit'); })]);
  application = undefined; page = undefined; void current.close().catch(() => {});
}
(async () => {
  fs.mkdirSync(files, { recursive: true }); fs.writeFileSync(config, `[default]\nauthtoken=${fakeSecret}\n`);
  const csc = path.join(process.env.SystemRoot, 'Microsoft.NET', 'Framework64', 'v4.0.30319', 'csc.exe');
  const compiled = spawnSync(csc, ['/nologo', '/target:exe', `/out:${exe}`, path.join(root, 'scripts', 'fixtures', 'FakeNatapp.cs')], { encoding: 'utf8', windowsHide: true });
  assert.equal(compiled.status, 0, compiled.stdout || compiled.stderr);
  const port = await freePort(), publicPort = await freePort();
  const appRoot = packaged ? path.join(path.dirname(binary), 'resources', 'gateway') : stage;
  const native = path.join(appRoot, 'controller', 'PrivateControlPipe.exe');
  assert.equal(await countNatappProcesses(native), 0, 'the fixture does not run alongside an existing NATAPP');
  manager = new ControllerGatewayManager({ appRoot, dataDir: path.join(data, 'gateway'), port, nodePath: packaged ? path.join(appRoot, 'runtime', 'node.exe') : binary, runAsNode: !packaged, startTimeoutMs: 15000 });
  const args = [...(packaged ? [] : ['.']), `--hajimink-data-dir=${data}`, `--hajimink-gateway-port=${port}`];
  async function launch() { application = await electron.launch({ executablePath: binary, args, cwd: root, timeout: 60000 }); page = await application.firstWindow(); await selectDesktopPage(page, 'gateway'); }
  await launch();
  await application.evaluate(({ dialog }, paths) => { dialog.showOpenDialog = async (_window, options) => ({ canceled: false, filePaths: [options.title.includes('客户端') ? paths.exe : paths.config] }); }, { exe, config });
  await page.selectOption('#gateway-provider', 'natapp');
  await waitForShellState(page, value => value.setup?.tunnelProvider === 'natapp');
  await page.locator('#natapp-manager-card').waitFor({ state: 'visible' });
  await selectDesktopPage(page, 'documentation');
  assert.match(await page.locator('#help-tunnels').textContent(), /费用以其实际方案为准/);
  assert.match(await page.locator('#help-tunnels').textContent(), /不显示客户端窗口/);
  await selectDesktopPage(page, 'gateway');
  await page.locator('#natapp-manager-card summary').click();
  await page.click('#natapp-select-binary'); await page.locator('#natapp-binary-path').getByText(/natapp\.exe/).waitFor();
  await page.click('#natapp-select-config'); await page.locator('#natapp-config-path').getByText(/config\.ini/).waitFor();
  await page.click('#natapp-save'); await page.locator('#natapp-feedback').getByText(/已保存/).waitFor();
  assert.equal(JSON.stringify(await page.evaluate(() => window.hajimink.state())).includes(fakeSecret), false);
  assert.equal(fs.readFileSync(path.join(data, 'gateway', 'natapp-settings.json'), 'utf8').includes(fakeSecret), false);
  assert.equal(await page.locator('#natapp-start').isDisabled(), true, 'local-only gateway must not start a tunnel');
  await setGatewayEnabled(page, true); await page.waitForFunction(() => document.querySelector('#gateway-state-badge')?.textContent === '正常', null, { timeout: 45000 });
  assert.equal(await page.locator('#natapp-start').isDisabled(), true);
  await page.locator('.gateway-address-help summary').click(); page.once('dialog', dialog => dialog.accept()); await page.click('#gateway-no-address');
  await waitForShellState(page, value => value.gateway?.state === 'ready' && value.gateway?.awaitingPublicOrigin === true, { timeoutMs: 45000 });
  await page.locator('#natapp-start').waitFor({ state: 'visible' });
  page.once('dialog', dialog => dialog.accept()); await page.click('#natapp-start');
  const running = await waitForShellState(page, value => value.gateway?.natapp?.state === 'running', { timeoutMs: 30000 });
  const pid = running.gateway.natapp.pid; assert.ok(pid);
  assert.match(await page.locator('#natapp-state').textContent(), /运行中.*检查远程入口/);
  assert.equal(await page.locator('#natapp-save').isDisabled(), true);
  assert.equal(fs.readFileSync(config, 'utf8').includes(fakeSecret), true);
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(820, 600));
  await page.locator('#natapp-manager-card').scrollIntoViewIfNeeded();
  const size = await page.locator('#gateway').evaluate(element => ({ scrollWidth: element.scrollWidth, width: element.clientWidth }));
  assert.ok(size.scrollWidth <= size.width + 1, 'NATAPP controls must fit the minimum window');
  const artifacts = path.join(stage, 'smoke-artifacts'); fs.mkdirSync(artifacts, { recursive: true });
  await page.emulateMedia({ colorScheme: 'light' }); await page.screenshot({ path: path.join(artifacts, 'natapp-managed-light.png') });
  await page.emulateMedia({ colorScheme: 'dark' }); await page.screenshot({ path: path.join(artifacts, 'natapp-managed-dark.png') });
  await page.emulateMedia({ colorScheme: 'no-preference' });
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1320, 850));
  await page.fill('#gateway-public-origin', `https://localhost:${publicPort}`);
  page.once('dialog', dialog => dialog.accept()); await page.click('#gateway-passkey-start');
  await page.locator('#gateway-setup-code-panel').waitFor({ state: 'visible', timeout: 60000 });
  const bound = await waitForShellState(page, value => value.gateway?.state === 'ready' && value.gateway?.awaitingPublicOrigin === false && value.gateway?.natapp?.state === 'running', { timeoutMs: 45000 });
  assert.equal(bound.gateway.natapp.pid, pid, 'binding a provider-issued address must not restart the tunnel');
  await quitDesktop();
  assert.equal(await countNatappProcesses(native), 1, 'closing desktop must leave the owned tunnel running');
  await launch();
  const attached = await waitForShellState(page, value => value.gateway?.natapp?.state === 'running', { timeoutMs: 45000 });
  assert.equal(attached.gateway.natapp.pid, pid);
  await page.selectOption('#gateway-provider', 'tailscale'); await waitForShellState(page, value => value.setup?.tunnelProvider === 'tailscale');
  assert.equal(await page.locator('#natapp-manager-card').isVisible(), true, 'an owned tunnel remains visible after provider switch');
  await page.locator('#natapp-manager-card summary').click();
  page.once('dialog', dialog => dialog.accept()); await page.click('#natapp-stop');
  await waitForShellState(page, value => value.gateway?.natapp?.state === 'stopped', { timeoutMs: 30000 });
  assert.equal(await countNatappProcesses(native), 0);
  await page.selectOption('#gateway-provider', 'natapp'); await waitForShellState(page, value => value.setup?.tunnelProvider === 'natapp');
  page.once('dialog', dialog => dialog.accept()); await page.click('#natapp-start');
  await waitForShellState(page, value => value.gateway?.natapp?.state === 'running', { timeoutMs: 30000 });
  page.once('dialog', dialog => dialog.accept()); await setGatewayEnabled(page, false);
  await page.waitForFunction(() => document.querySelector('#gateway-state-badge')?.textContent === '未启动', null, { timeout: 30000 });
  await waitForShellState(page, value => value.gateway?.natapp?.state === 'stopped', { timeoutMs: 15000 });
  assert.equal(await countNatappProcesses(native), 0, 'stopping gateway must stop its own NATAPP first');
  console.log(JSON.stringify({ desktop: packaged ? 'packaged' : 'development', provider: 'fake-natapp', fileSelection: 'passed', protectedStart: 'passed', addressBindingRetainsTunnel: 'passed', reattach: 'passed', switchVisibility: 'passed', stopOrder: 'passed', realProvider: 'not tested' }));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (manager) { try { await manager.stop(); } catch {} manager.close(); }
  if (application) { try { await quitDesktop(); } catch (error) { console.error(error.message); process.exitCode = 1; } }
  const dir = path.join(data, 'gateway');
  if (['controller.instance.json', 'gateway.instance.lock', 'natapp.instance.json'].some(name => fs.existsSync(path.join(dir, name)))) { console.error('Fixture instances unconfirmed; retained:', temp); process.exitCode = 1; return; }
  const actual = fs.realpathSync(temp), base = fs.realpathSync(os.tmpdir());
  if (path.dirname(actual).toLowerCase() !== base.toLowerCase() || !path.basename(actual).startsWith('hajimink-natapp-ui-')) throw new Error('Unexpected fixture path');
  fs.rmSync(actual, { recursive: true, force: true });
});
